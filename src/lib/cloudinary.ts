/**
 * Cloudinary utilities for Sohba (صُحبة)
 * Handles image optimization, secure client uploads via serverless signature,
 * and safe image deletion.
 */

export const ALLOWED_IMAGE_TYPES = [
  'image/jpeg',
  'image/png',
  'image/webp',
  'image/gif',
  'image/heic',
  'image/heif',
];

export const MAX_IMAGE_FILE_SIZE_BYTES = 10 * 1024 * 1024; // 10 MB

/**
 * Checks whether an image URL is hosted on Cloudinary
 */
export function isCloudinaryUrl(url: string | null | undefined): boolean {
  if (!url) return false;
  return url.includes('res.cloudinary.com') || url.includes('cloudinary.com');
}

/**
 * Extracts the public_id (including folder path) from a Cloudinary URL
 * e.g. https://res.cloudinary.com/demo/image/upload/v1234/sohba/posts/uid/abc.jpg -> sohba/posts/uid/abc
 */
export function extractCloudinaryPublicId(url: string | null | undefined): string | null {
  if (!url || !isCloudinaryUrl(url)) return null;

  try {
    const uploadIndex = url.indexOf('/upload/');
    if (uploadIndex === -1) return null;

    let pathPart = url.substring(uploadIndex + '/upload/'.length);

    // Remove query params if any
    pathPart = pathPart.split('?')[0];

    // Remove any transformation parameters before version or folder
    // Transformation segments typically look like c_limit,w_1080/...
    const segments = pathPart.split('/');
    const cleanedSegments: string[] = [];
    let passedTransformations = false;

    for (const seg of segments) {
      // Check if segment is a version string (v followed by digits)
      if (/^v\d+$/.test(seg)) {
        passedTransformations = true;
        continue;
      }
      // Check if segment is a transformation string (e.g., contains comma or underscore like c_limit,w_100,f_auto)
      if (!passedTransformations && (seg.includes(',') || /^[a-z]{1,3}_/.test(seg))) {
        continue;
      }
      passedTransformations = true;
      cleanedSegments.push(seg);
    }

    if (cleanedSegments.length === 0) return null;

    const fullPathWithExt = cleanedSegments.join('/');
    // Strip file extension (.jpg, .png, etc.)
    const lastDotIndex = fullPathWithExt.lastIndexOf('.');
    return lastDotIndex !== -1 ? fullPathWithExt.substring(0, lastDotIndex) : fullPathWithExt;
  } catch {
    return null;
  }
}

export type OptimizeImageOptions = {
  width?: number;
  height?: number;
  crop?: 'limit' | 'fill' | 'scale' | 'thumb';
  quality?: 'auto' | number;
  format?: 'auto' | 'webp' | 'jpg';
};

/**
 * Returns an optimized Cloudinary URL with auto-format and auto-quality.
 * For legacy Supabase Storage or non-Cloudinary URLs, returns the original URL untouched.
 */
export function getOptimizedPostImageUrl(
  url: string | null | undefined,
  options?: OptimizeImageOptions
): string {
  if (!url) return '';
  if (!isCloudinaryUrl(url)) return url; // Retain legacy Supabase Storage URLs as-is!

  const width = options?.width;
  const height = options?.height;
  const crop = options?.crop ?? (width && height ? 'fill' : 'limit');

  const transforms: string[] = ['f_auto', 'q_auto'];

  if (width && height) {
    transforms.unshift(`c_${crop},w_${width},h_${height}`);
  } else if (width) {
    transforms.unshift(`c_${crop},w_${width}`);
  }

  const transformString = transforms.join(',');

  // Insert transformations right after /upload/
  // Handle both /image/upload/ and /upload/
  if (url.includes('/upload/')) {
    // If the URL already contains our exact transformation, avoid duplicating
    if (url.includes(`/upload/${transformString}/`)) {
      return url;
    }

    // Replace /upload/ with /upload/<transformations>/
    // If there are already transformations, prepend or replace
    return url.replace(/\/upload\/(?:[a-z]{1,3}_[^/]+\/)?/, `/upload/${transformString}/`);
  }

  return url;
}

export type CloudinaryUploadResult = {
  url: string;
  publicId: string;
  bytes: number;
  format: string;
  width: number;
  height: number;
};

/**
 * Uploads an image to Cloudinary using a secure signed request generated by our backend.
 * Includes client-side validation, progress tracking, and robust error handling.
 */
export async function uploadPostImageToCloudinary(
  file: File,
  accessToken: string,
  onProgress?: (progressPercent: number) => void
): Promise<CloudinaryUploadResult> {
  // 1. Client-side file validations
  if (!file) {
    throw new Error('يرجى تحديد ملف صورة للرفع.');
  }

  if (file.size > MAX_IMAGE_FILE_SIZE_BYTES) {
    throw new Error('حجم الصورة كبير جدًا؛ الحد الأقصى المسموح به هو 10 ميجابايت.');
  }

  const fileType = file.type.toLowerCase();
  const isImage = fileType.startsWith('image/') || ALLOWED_IMAGE_TYPES.some((t) => fileType.includes(t));
  if (!isImage) {
    throw new Error('نوع الملف غير مدعوم. يرجى اختيار ملف صورة صالح (JPG, PNG, WEBP, GIF).');
  }

  // 2. Request a signed upload signature from our backend
  let signData: {
    signature: string;
    timestamp: number;
    folder: string;
    apiKey: string;
    cloudName: string;
    uploadUrl: string;
  };

  try {
    const signRes = await fetch('/api/cloudinary-sign', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        Authorization: `Bearer ${accessToken}`,
      },
    });

    if (!signRes.ok) {
      let errorMsg = 'تعذّر الاتصال بخادم توقيع الرفع.';
      try {
        const errJson = await signRes.json();
        if (errJson?.error) errorMsg = errJson.error;
      } catch {
        // use default
      }
      throw new Error(errorMsg);
    }

    signData = await signRes.json();
  } catch (err: any) {
    console.error('Failed to get Cloudinary signature:', err);
    throw new Error(err.message || 'تعذّر الحصول على تصريح رفع الصورة.');
  }

  // 3. Perform the signed upload directly to Cloudinary with progress tracking
  return new Promise((resolve, reject) => {
    const xhr = new XMLHttpRequest();
    const formData = new FormData();

    formData.append('file', file);
    formData.append('api_key', signData.apiKey);
    formData.append('timestamp', String(signData.timestamp));
    formData.append('folder', signData.folder);
    formData.append('signature', signData.signature);

    xhr.upload.onprogress = (e) => {
      if (e.lengthComputable && onProgress) {
        const percent = Math.min(100, Math.max(0, Math.round((e.loaded / e.total) * 100)));
        onProgress(percent);
      }
    };

    xhr.onload = () => {
      if (xhr.status >= 200 && xhr.status < 300) {
        try {
          const res = JSON.parse(xhr.responseText);
          resolve({
            url: res.secure_url || res.url,
            publicId: res.public_id,
            bytes: res.bytes || file.size,
            format: res.format,
            width: res.width,
            height: res.height,
          });
        } catch {
          reject(new Error('تعذّر قراءة استجابة خادم الصور.'));
        }
      } else {
        let msg = `فشل رفع الصورة إلى Cloudinary (${xhr.status})`;
        try {
          const errRes = JSON.parse(xhr.responseText);
          if (errRes.error?.message) {
            msg = `خطأ في Cloudinary: ${errRes.error.message}`;
          }
        } catch {
          // ignore
        }
        reject(new Error(msg));
      }
    };

    xhr.onerror = () => {
      reject(new Error('انقطع الاتصال بخادم Cloudinary أثناء رفع الصورة. تحقق من اتصالك بالإنترنت.'));
    };

    xhr.ontimeout = () => {
      reject(new Error('انتهت مهلة رفع الصورة. يرجى المحاولة مرة أخرى.'));
    };

    xhr.timeout = 60000; // 60 seconds
    xhr.open('POST', signData.uploadUrl, true);
    xhr.send(formData);
  });
}

export interface CloudinaryDeleteResponse {
  ok: boolean;
  deleted?: boolean;
  skipped?: boolean;
  result?: string;
  message?: string;
  error?: string;
}

/**
 * Securely deletes a post image from Cloudinary via our backend endpoint
 */
export async function deletePostImageFromCloudinary(
  imageUrlOrPublicId: string,
  accessToken: string,
  postId?: string,
  explicitPublicId?: string | null
): Promise<CloudinaryDeleteResponse> {
  if (!imageUrlOrPublicId && !explicitPublicId) {
    return { ok: false, error: 'No image identifier provided' };
  }

  const publicId =
    explicitPublicId ||
    (isCloudinaryUrl(imageUrlOrPublicId)
      ? extractCloudinaryPublicId(imageUrlOrPublicId)
      : imageUrlOrPublicId);

  if (!publicId) {
    return { ok: false, error: 'Could not extract valid public_id' };
  }

  try {
    const res = await fetch('/api/cloudinary-delete', {
      method: 'POST',
      keepalive: true,
      headers: {
        'Content-Type': 'application/json',
        Authorization: `Bearer ${accessToken}`,
      },
      body: JSON.stringify({
        publicId,
        imageUrl: isCloudinaryUrl(imageUrlOrPublicId) ? imageUrlOrPublicId : undefined,
        postId,
      }),
    });

    const data = await res.json().catch(() => ({}));

    if (!res.ok) {
      console.warn('[cloudinary] Image deletion returned non-OK status:', res.status, data);
      return {
        ok: false,
        deleted: false,
        error: data.error || `HTTP error ${res.status}`,
      };
    }

    return {
      ok: true,
      deleted: data.deleted ?? true,
      skipped: data.skipped ?? false,
      result: data.result,
      message: data.message,
    };
  } catch (err: any) {
    console.warn('[cloudinary] Failed to call delete API:', err);
    return {
      ok: false,
      deleted: false,
      error: err.message || 'Network error calling delete endpoint',
    };
  }
}

/**
 * Trigger processing of pending Cloudinary deletion tasks
 */
export async function triggerCloudinaryQueueProcess(
  accessToken: string,
  limit = 50
): Promise<{ ok: boolean; message?: string; result?: any; error?: string }> {
  try {
    const res = await fetch(`/api/cloudinary-process-queue?limit=${limit}`, {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${accessToken}`,
      },
    });

    const data = await res.json().catch(() => ({}));
    if (!res.ok) {
      return { ok: false, error: data.error || `HTTP error ${res.status}` };
    }

    return { ok: true, message: data.message, result: data.result };
  } catch (err: any) {
    return { ok: false, error: err.message || 'Failed to trigger queue processing' };
  }
}

/**
 * Fetch current deletion queue statistics
 */
export async function getCloudinaryQueueStats(
  accessToken: string
): Promise<{ pending: number; failed: number; completed: number; skipped: number; total: number } | null> {
  try {
    const res = await fetch('/api/cloudinary-process-queue?stats=true', {
      headers: {
        Authorization: `Bearer ${accessToken}`,
      },
    });

    if (!res.ok) return null;
    const data = await res.json().catch(() => ({}));
    return data.stats || null;
  } catch {
    return null;
  }
}
